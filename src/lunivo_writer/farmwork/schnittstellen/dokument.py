"""Anzeige-Port für Befehle, die am Dokument im Editor arbeiten: der Editor, wie ihn die Programmkern-Funktionen unter ``editor/`` erwarten.

Die Oberfläche setzt diesen Vertrag um (``KernEditor`` erfüllt ihn strukturell). Das Farmwork reicht den Editor an die Funktionen des Programmkerns
weiter und benutzt selbst nur die hier genannten Mitglieder; die Oberfläche bekommt nie ein Objekt des Programmkerns zurück."""
from __future__ import annotations

from typing import Protocol


class EditorPort(Protocol):
    quellen: list
    zitierweise: str

    def quelle_hinzufuegen(self, quelle: dict) -> None: ...

    def quelle_entfernen(self, tag: str) -> None: ...

    def document(self) -> object:
        """Das Dokument des Editors (Änderungsstatus ``setModified``)."""

    def textCursor(self) -> object:
        """Die Schreibmarke (Auswahl, Tabelle an der Marke)."""

    def apply_style(self, name: str) -> None: ...

    def absatzformat(self) -> dict: ...

    def note_springen(self, delta: int, art: str | None = None): ...

    def note_neu(self, art: str, text: str) -> int: ...

    # Kommentare
    kommentare: list

    def kommentar_springen(self, delta: int) -> None: ...

    def kommentar_am_cursor(self): ...

    def kommentar_loeschen(self, kid) -> None: ...

    def kommentare_alle_loeschen(self) -> None: ...

    # nachverfolgte Änderungen
    verfolgen: bool
    markup: bool

    def set_verfolgen(self, an: bool) -> None: ...

    def set_markup(self, an: bool) -> None: ...

    def aenderung_springen(self, delta: int): ...

    def aenderung_am_cursor(self): ...

    def aenderung_annehmen(self, aenderung, annehmen: bool) -> None: ...

    def alle_aenderungen(self, annehmen: bool) -> int: ...

    def angezeigte_aenderungen(self, annehmen: bool) -> int: ...

    def aenderungen(self) -> list: ...

    def aenderung_sichtbar(self, aenderung) -> bool: ...

    def kommentar_bereiche(self) -> list: ...

    markup_filter: dict

    def markup_filter_setzen(self, **werte) -> None: ...

    sitzung: object

    # Zwischenablage und Auswahl
    def paste(self) -> None: ...

    def cut(self) -> None: ...

    def copy(self) -> None: ...

    def selectAll(self) -> None: ...

    def _kf(self):
        """Das Eingabefeld der Kopf- und Fußzeile, wenn dort gerade bearbeitet wird, sonst ``None``."""

    def tabelle_ohne_rahmen_waehlen(self) -> bool: ...

    def aehnlich_formatiert(self) -> list: ...

    def set_suchtreffer(self, treffer: list) -> None: ...

    def select_range(self, von: int, bis: int) -> None: ...

    # Ansicht
    zoom: float
    marken: bool
    gliederung: bool

    def set_zoom(self, wert: float) -> None: ...

    def set_gliederung(self, an: bool) -> None: ...

    def set_versteckt(self, an: bool) -> None: ...

    def ist_versteckt(self) -> bool: ...
